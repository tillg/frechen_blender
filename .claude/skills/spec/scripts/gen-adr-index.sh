#!/usr/bin/env bash
# Regenerate specs/architecture/index.md from the live ADRs' frontmatter.
# Usage: gen-adr-index.sh [--check]   — --check exits 1 when the index is stale. Run from the repo root.
set -euo pipefail
dir="specs/architecture"
out="$dir/index.md"
mkdir -p "$dir"
field() { sed -n "s/^$2: *//p" "$1" | head -1 | sed -e 's/^"//' -e 's/"$//'; }
gen() {
  echo "# Architecture decisions"
  echo
  echo "<!-- GENERATED by .claude/skills/spec/scripts/gen-adr-index.sh — do not edit. -->"
  echo
  echo "## Live"
  echo
  local any=0
  for f in $(ls "$dir"/adr-*.md 2>/dev/null | sort); do
    any=1
    echo "* [$(field "$f" id): $(field "$f" title)]($(basename "$f")) - $(field "$f" description) ($(field "$f" status), $(field "$f" date))"
  done
  [[ $any == 1 ]] || echo "_No ADRs yet. \`/spec:propose\` or \`/spec:grill\` create one when a decision earns it._"
  if ls "$dir"/archive/adr-*.md >/dev/null 2>&1; then
    echo
    echo "## Archive"
    echo
    for f in $(ls "$dir"/archive/adr-*.md | sort); do
      echo "* [$(field "$f" id): $(field "$f" title)](archive/$(basename "$f")) ($(field "$f" status))"
    done
  fi
}
if [[ "${1:-}" == "--check" ]]; then
  diff -u "$out" <(gen) >/dev/null 2>&1 || { echo "$out is stale — run gen-adr-index.sh" >&2; exit 1; }
  echo "$out is current"
else
  gen >"$out"
  echo "wrote $out"
fi
