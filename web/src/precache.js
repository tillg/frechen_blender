// The offline store of the production build (issue #56, ADR-004-CTPY): which files the service
// worker keeps, in which cache, and the generated sw.js. Pure; offline-build.js feeds it the files of
// web/dist after `vite build`. The live build is one cache, named by the content hash of its files
// and the worker body; each plan version (v/<id>/…, issue #59) is a cache of its own, named by the
// hash of its files only, so a deploy that leaves a version alone leaves its cache alone.
import { createHash } from 'node:crypto';

const WORKER = 'sw.js', PREFIX = 'frechenlehen-';

// paths relative to dist (posix) -> the URLs the worker fetches, relative to its scope
export function precacheList(paths) {
  return paths.filter((p) => p !== WORKER)
    .map((p) => encodeURI(p).replace(/%5B/g, '[').replace(/%5D/g, ']').replace(/[?#]/g, encodeURIComponent)).sort();
}

// [[path, bytes], ...] -> 12 hex digits, independent of the order
export function contentHash(entries) {
  const h = createHash('sha256');
  for (const [p, bytes] of [...entries].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    h.update(p); h.update('\0'); h.update(bytes); h.update('\0');
  }
  return h.digest('hex').slice(0, 12);
}

// [[path, bytes], ...] of dist (without sw.js) + the worker body -> {cache name: [URLs]}
export function cacheGroups(entries, body) {
  const live = [], versions = {};
  for (const e of entries) {
    if (e[0] === WORKER) continue;
    const id = e[0].match(/^v\/([^/]+)\//)?.[1];
    if (id) (versions[id] ??= []).push(e); else live.push(e);
  }
  const groups = { [PREFIX + contentHash([...live, [`\0${WORKER}`, new TextEncoder().encode(body)]])]: live };
  for (const [id, files] of Object.entries(versions).sort()) groups[`${PREFIX}v-${id}-${contentHash(files)}`] = files;
  return Object.fromEntries(Object.entries(groups).map(([name, files]) => [name, precacheList(files.map(([p]) => p))]));
}

export function workerSource(caches, body) {
  return `// generated by web/offline-build.js from web/dist; body: web/src/sw.js\n`
    + `const CACHES = ${JSON.stringify(caches)};\n\n${body}\n`;
}

// [[path, bytes], ...] of dist (without sw.js) + the worker body -> sw.js
export const buildWorker = (entries, body) => workerSource(cacheGroups(entries, body), body);
