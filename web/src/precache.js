// The offline store of the production build (issue #56, ADR-004-CTPY): which files the service
// worker keeps, the build's content hash and the generated sw.js. Pure; offline-build.js feeds it
// the files of web/dist after `vite build`.
import { createHash } from 'node:crypto';

const WORKER = 'sw.js';

// paths relative to dist (posix) -> the URLs the worker fetches, relative to its scope
export function precacheList(paths) {
  return paths.filter((p) => p !== WORKER)
    .map((p) => encodeURI(p).replace(/%5B/g, '[').replace(/%5D/g, ']').replace(/[?#]/g, encodeURIComponent)).sort();
}

// [[path, bytes], ...] -> 12 hex digits, independent of the order
export function contentHash(entries) {
  const h = createHash('sha256');
  for (const [p, bytes] of [...entries].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    h.update(p); h.update('\0'); h.update(bytes); h.update('\0');
  }
  return h.digest('hex').slice(0, 12);
}

export function workerSource(version, files, body) {
  return `// generated by web/offline-build.js from web/dist; body: web/src/sw.js\n`
    + `const VERSION = ${JSON.stringify(version)};\nconst FILES = ${JSON.stringify(files)};\n\n${body}\n`;
}

// [[path, bytes], ...] of dist (without sw.js) + the worker body -> sw.js; the version covers the body too
export function buildWorker(entries, body) {
  const version = contentHash([...entries, [`\0${WORKER}`, new TextEncoder().encode(body)]]);
  return workerSource(version, precacheList(entries.map(([p]) => p)), body);
}
